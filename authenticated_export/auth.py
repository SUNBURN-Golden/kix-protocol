"""Fixture HMAC-SHA256 authentication of the export manifest (contract §4).

Mirrors onsale/tokens.py exactly: the signature is a fixture HMAC-SHA256 over
the canonical unsigned body with a caller-supplied key; the keyVersion label
is part of the signed body. Keys are generated by the caller (tests) and are
never committed or stored. A hash alone proves neither authorized authorship
nor latest state: the production signing scheme, trust root and registry
boundary are DECISION_REQUIRED · Astra; this module chooses none of them.
"""

from __future__ import annotations

import hashlib
import hmac

from readiness.codec import CodecError, canonical_json

from authenticated_export.errors import ExportError
from authenticated_export.manifest import unsigned_body


def _check_key(key, key_version):
    if not isinstance(key, bytes) or not key:
        raise ExportError('EXPORT_KEY')
    if not isinstance(key_version, str) or not key_version:
        raise ExportError('EXPORT_KEY_VERSION')


def sign(manifest, key, key_version):
    """Return a new manifest document with the fixture signature attached.

    The body must already carry its manifestHash (build_manifest binds it).
    """
    _check_key(key, key_version)
    body = unsigned_body(manifest)
    if body['keyVersion'] != key_version:
        raise ExportError('EXPORT_KEY_VERSION')
    digest = hmac.new(key, canonical_json(body).encode('utf-8'), hashlib.sha256).hexdigest()
    signed = dict(manifest)
    signed['signature'] = digest
    return signed


def verify(manifest, key):
    """True only when the signature matches the canonical unsigned body."""
    if not isinstance(manifest, dict) or not isinstance(manifest.get('signature'), str):
        return False
    try:
        body = unsigned_body(manifest)
    except ExportError:
        return False
    if not isinstance(key, bytes) or not key:
        return False
    try:
        expected = hmac.new(
            key, canonical_json(body).encode('utf-8'), hashlib.sha256,
        ).hexdigest()
    except (CodecError, TypeError, ValueError):
        return False
    return hmac.compare_digest(expected, manifest['signature'])
