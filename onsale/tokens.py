"""Admission token structure and fixture signing (contract §4).

Field names are exactly the contract's: showId / queueTicketId /
queuePositionIdentity / inventoryEpoch / inventoryMode /
authorityPlacementVersion / shardId / nonce / issuedAt / expiresAt /
signature / keyVersion. The signature is a fixture HMAC-SHA256 over the
canonical unsigned body with a caller-supplied key; the keyVersion label is
part of the signed body. Keys are generated by the caller (tests) and are
never committed or stored. The production signature scheme and key
management are DECISION_REQUIRED · Astra (contract §10); this module chooses
neither. A signed token gates an attempt; it is never proof of a single
execution by itself — the authoritative commit checks the token state.
"""

from __future__ import annotations

import hashlib
import hmac

from readiness.codec import canonical_json

# The contract §4 fields, in contract order. signature is the only field
# outside the signed body.
TOKEN_FIELDS = (
    'showId', 'queueTicketId', 'queuePositionIdentity', 'inventoryEpoch',
    'inventoryMode', 'authorityPlacementVersion', 'shardId', 'nonce',
    'issuedAt', 'expiresAt', 'signature', 'keyVersion',
)
_BODY_FIELDS = tuple(name for name in TOKEN_FIELDS if name != 'signature')


class TokenError(ValueError):
    def __init__(self, code):
        super().__init__(code)
        self.code = code


def _check_key(key, key_version):
    if not isinstance(key, bytes) or not key:
        raise TokenError('TOKEN_KEY')
    if not isinstance(key_version, str) or not key_version:
        raise TokenError('TOKEN_KEY_VERSION')


def unsigned_body(token):
    """The canonical signed body: every §4 field except the signature."""
    missing = [name for name in _BODY_FIELDS if name not in token]
    if missing:
        raise TokenError('TOKEN_FIELDS')
    return {name: token[name] for name in _BODY_FIELDS}


def sign(token, key, key_version):
    """Return a new token document with the fixture signature attached."""
    _check_key(key, key_version)
    body = unsigned_body(token)
    if body['keyVersion'] != key_version:
        raise TokenError('TOKEN_KEY_VERSION')
    digest = hmac.new(key, canonical_json(body).encode('utf-8'), hashlib.sha256).hexdigest()
    signed = dict(token)
    signed['signature'] = digest
    return signed


def verify(token, key):
    """True only when the signature matches the canonical unsigned body."""
    if not isinstance(token, dict) or not isinstance(token.get('signature'), str):
        return False
    try:
        body = unsigned_body(token)
    except TokenError:
        return False
    if not isinstance(key, bytes) or not key:
        return False
    expected = hmac.new(key, canonical_json(body).encode('utf-8'), hashlib.sha256).hexdigest()
    return hmac.compare_digest(expected, token['signature'])


def token_id(queue_ticket_id, nonce):
    """Stable local identifier of one issued token (ticket + nonce)."""
    if not isinstance(queue_ticket_id, str) or not queue_ticket_id:
        raise TokenError('TOKEN_FIELDS')
    if not isinstance(nonce, str) or not nonce:
        raise TokenError('TOKEN_FIELDS')
    return 'tok-' + hashlib.sha256(
        canonical_json([queue_ticket_id, nonce]).encode('utf-8'),
    ).hexdigest()[:16]
